"""Builds item data from PokeAPI's CSV files:
  source/data/tmdata.hpp  - the move taught by each TM/TR, per game
  romfs/items/desc_<lang>.txt     - item descriptions (by game item id), en/es/fr
  romfs/abilities/desc_<lang>.txt - ability descriptions (by ability id), en/es/fr

Usage: python tools/gen_itemdata.py <folder with machines.csv, items.csv,
       item_game_indices.csv, item_flavor_text.csv and ability_flavor_text.csv>
The CSVs are in https://github.com/PokeAPI/pokeapi/tree/master/data/v2/csv
"""
import csv
import os
import re
import sys

src = sys.argv[1]
root = os.path.join(os.path.dirname(__file__), "..")


def rows(name):
    with open(os.path.join(src, name + ".csv"), encoding="utf-8") as f:
        return list(csv.DictReader(f))


items = {r["id"]: r["identifier"] for r in rows("items")}

# --- TMs: version groups 19 LGPE, 20 SwSh, 25-27 SV (+DLC), 30 Z-A
tables = {"LGPE_TM": {}, "SWSH_TM": {}, "SWSH_TR": {}, "SV_TM": {}, "ZA_TM": {}}
for r in rows("machines"):
    ident = items.get(r["item_id"], "")
    m = re.fullmatch(r"(tm|tr)(\d+)", ident)
    if not m:
        continue
    kind, num, move = m.group(1), int(m.group(2)), int(r["move_id"])
    vg = r["version_group_id"]
    if vg == "19" and kind == "tm":
        tables["LGPE_TM"][num] = move
    elif vg == "20":
        tables["SWSH_TM" if kind == "tm" else "SWSH_TR"][num] = move
    elif vg in ("25", "26", "27") and kind == "tm":
        tables["SV_TM"][num] = move
    elif vg == "30" and kind == "tm":
        tables["ZA_TM"][num] = move

out = os.path.join(root, "source", "data", "tmdata.hpp")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/gen_itemdata.py from PokeAPI's machines.csv. Do not edit.\n")
    f.write("// The move (game move id) taught by TM/TR number N; 0 where there is none.\n")
    f.write("#pragma once\n\n#include <switch.h>\n\nnamespace monhex::data\n{\n")
    for name, table in tables.items():
        size = (max(table) + 1) if table else 1
        values = ", ".join(str(table.get(i, 0)) for i in range(size))
        f.write(f"    constexpr u16 {name}[{size}] = {{{values}}};\n")
    f.write("}\n")
print("TMs:", {k: len(v) for k, v in tables.items()})

# --- Descriptions: game item id -> PokeAPI item, newest English text
index = {}
gens = {}
for r in rows("item_game_indices"):
    gens.setdefault(r["generation_id"], {})[int(r["game_index"])] = r["item_id"]
for gen in ("8", "9", "7", "6", "5", "4"):
    for game_id, item_id in gens.get(gen, {}).items():
        index.setdefault(game_id, item_id)

LANGS = {"en": "9", "es": "7", "fr": "5"}  # PokeAPI language ids


def newest(name, key):
    """Newest description per id and language: {lang: {id: text}}"""
    out = {code: {} for code in LANGS}
    best = {}
    for r in rows(name):
        for code, lid in LANGS.items():
            if r["language_id"] != lid:
                continue
            vg = int(r["version_group_id"])
            k = (code, r[key])
            if k not in best or vg >= best[k]:
                best[k] = vg
                out[code][r[key]] = " ".join(r["flavor_text"].split())
    return out


items_text = newest("item_flavor_text", "item_id")
os.makedirs(os.path.join(root, "romfs", "items"), exist_ok=True)
for code, texts in items_text.items():
    count = 0
    with open(os.path.join(root, "romfs", "items", f"desc_{code}.txt"), "w", encoding="utf-8", newline=chr(10)) as f:
        for game_id in sorted(index):
            t = texts.get(index[game_id])
            if t:
                f.write(f"{game_id}|{t}" + chr(10))
                count += 1
    print(f"item descriptions ({code}):", count)

# --- Abilities: PokeAPI ability ids are the games' ids
abilities_text = newest("ability_flavor_text", "ability_id")
os.makedirs(os.path.join(root, "romfs", "abilities"), exist_ok=True)
for code, texts in abilities_text.items():
    with open(os.path.join(root, "romfs", "abilities", f"desc_{code}.txt"), "w", encoding="utf-8", newline=chr(10)) as f:
        for aid in sorted(texts, key=int):
            if int(aid) < 10000:
                f.write(f"{aid}|{texts[aid]}" + chr(10))
    print(f"ability descriptions ({code}):", len(texts))
