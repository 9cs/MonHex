"""Builds source/data/movedata.hpp (type, category, power and PP of each move)
from PokeAPI's moves.csv. Usage: python tools/gen_movedata.py path/to/moves.csv
The CSV is at https://github.com/PokeAPI/pokeapi/blob/master/data/v2/csv/moves.csv
"""
import csv
import os
import sys

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), "..", "source", "data", "movedata.hpp")

rows = {}
with open(src, encoding="utf-8") as f:
    for r in csv.DictReader(f):
        mid = int(r["id"])
        if mid >= 10000:  # shadow moves and other non-game entries
            continue
        type_id = int(r["type_id"])
        rows[mid] = (
            type_id - 1 if 1 <= type_id <= 18 else 255,      # PokeAPI 1..18 -> game 0..17
            {"1": 0, "2": 1, "3": 2}.get(r["damage_class_id"], 0),  # status/physical/special
            int(r["power"] or 0),
            int(r["pp"] or 0),
            int(r["accuracy"] or 0),
        )

count = max(rows) + 1
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/gen_movedata.py from PokeAPI's moves.csv. Do not edit.\n")
    f.write("#pragma once\n\n#include <switch.h>\n\nnamespace monhex::data\n{\n")
    f.write("    struct MoveInfo\n    {\n        u8 type;     // 0..17 in game order, 255 unknown\n")
    f.write("        u8 category; // 0 status, 1 physical, 2 special\n        u8 power;    // 0 when it has none\n")
    f.write("        u8 pp;\n        u8 accuracy; // 0 when it never misses\n    };\n\n")
    f.write(f"    constexpr u16 MOVE_COUNT = {count};\n")
    f.write("    constexpr MoveInfo MOVES[MOVE_COUNT] = {\n")
    for i in range(count):
        t, c, p, pp, acc = rows.get(i, (255, 0, 0, 0, 0))
        f.write(f"        {{{t}, {c}, {p}, {pp}, {acc}}},\n")
    f.write("    };\n}\n")
print(f"{count} golpes em {os.path.normpath(out)}")
